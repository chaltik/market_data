CREATE SCHEMA IF NOT EXISTS weather;

-- Immutable source snapshots make later NOAA revisions auditable.
CREATE TABLE IF NOT EXISTS weather.source_snapshots (
    snapshot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name TEXT NOT NULL,
    source_file TEXT NOT NULL,
    source_url TEXT NOT NULL,
    source_processing_date DATE,
    retrieved_at TIMESTAMPTZ NOT NULL,
    sha256 TEXT NOT NULL,
    raw_content BYTEA NOT NULL,
    release_date DATE,
    release_date_confidence TEXT NOT NULL DEFAULT 'unknown',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (source_name, source_file, sha256)
);

CREATE TABLE IF NOT EXISTS weather.snapshot_bundles (
    bundle_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    retrieved_at TIMESTAMPTZ NOT NULL,
    nclimdiv_processing_date DATE NOT NULL,
    tavg_snapshot_id BIGINT NOT NULL REFERENCES weather.source_snapshots(snapshot_id),
    hdd_snapshot_id BIGINT NOT NULL REFERENCES weather.source_snapshots(snapshot_id),
    cdd_snapshot_id BIGINT NOT NULL REFERENCES weather.source_snapshots(snapshot_id),
    population_snapshot_id BIGINT NOT NULL REFERENCES weather.source_snapshots(snapshot_id),
    dc_station_snapshot_id BIGINT NOT NULL REFERENCES weather.source_snapshots(snapshot_id),
    release_date DATE,
    release_date_confidence TEXT NOT NULL DEFAULT 'unknown',
    availability_note TEXT NOT NULL,
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (tavg_snapshot_id, hdd_snapshot_id, cdd_snapshot_id,
            population_snapshot_id, dc_station_snapshot_id)
);

CREATE TABLE IF NOT EXISTS weather.census_region_state_crosswalk (
    state_abbrev CHAR(2) PRIMARY KEY,
    state_name TEXT NOT NULL,
    census_region TEXT NOT NULL CHECK (census_region IN ('Northeast','Midwest','South','West')),
    noaa_state_code SMALLINT,
    population_2010 BIGINT NOT NULL CHECK (population_2010 > 0),
    population_source TEXT NOT NULL,
    included_in_contiguous_us BOOLEAN NOT NULL DEFAULT TRUE,
    is_dc_proxy BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS weather.monthly_observations (
    bundle_id BIGINT NOT NULL REFERENCES weather.snapshot_bundles(bundle_id),
    geography_type TEXT NOT NULL CHECK (geography_type IN ('state','census_region')),
    geography_code TEXT NOT NULL,
    geography_name TEXT NOT NULL,
    census_region TEXT,
    reference_month DATE NOT NULL CHECK (EXTRACT(DAY FROM reference_month) = 1),
    mean_temperature_f NUMERIC,
    hdd65_f_days NUMERIC,
    cdd65_f_days NUMERIC,
    source_method TEXT NOT NULL,
    weighting_method TEXT NOT NULL,
    weighting_year SMALLINT,
    population_coverage_ratio NUMERIC,
    expected_member_count SMALLINT,
    observed_member_count SMALLINT,
    is_proxy BOOLEAN NOT NULL DEFAULT FALSE,
    availability_date DATE,
    availability_confidence TEXT NOT NULL DEFAULT 'unknown',
    PRIMARY KEY (bundle_id, geography_type, geography_code, reference_month)
);

CREATE INDEX IF NOT EXISTS monthly_observations_region_month_idx
    ON weather.monthly_observations (geography_type, geography_code, reference_month DESC);

COMMENT ON SCHEMA weather IS
    'Observed monthly U.S. temperature and degree-day history; source vintages and uncertain release timing are retained.';
COMMENT ON TABLE weather.monthly_observations IS
    'NOAA nClimDiv state monthly values and derived Census 4-region rollups. Region temperature starts from NOAA area-weighted state means; state values are combined using 2010 Census population weights. HDD/CDD are source-provided daily-thresholded monthly totals, not derived from monthly mean temperature. DC is a marked station proxy.';
