-- Non-destructive Yahoo options quote pilot.
-- No DROP statements. Existing definitions are not migrated by IF NOT EXISTS.
BEGIN;

CREATE SCHEMA IF NOT EXISTS options_data;

CREATE TABLE IF NOT EXISTS options_data.collection_runs (
    run_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at            TIMESTAMPTZ,
    status                 TEXT NOT NULL CHECK (status IN ('running', 'complete', 'partial', 'rate_limited', 'failed')),
    universe_code          TEXT NOT NULL,
    universe_asof          DATE NOT NULL,
    symbols_requested      INTEGER NOT NULL,
    symbols_completed      INTEGER NOT NULL DEFAULT 0,
    expirations_seen       INTEGER NOT NULL DEFAULT 0,
    expirations_completed  INTEGER NOT NULL DEFAULT 0,
    contracts_seen         INTEGER NOT NULL DEFAULT 0,
    contracts_retained     INTEGER NOT NULL DEFAULT 0,
    filters                JSONB NOT NULL,
    symbol_stats           JSONB NOT NULL DEFAULT '{}'::jsonb,
    error_text             TEXT,
    table_bytes_before     BIGINT,
    table_bytes_after      BIGINT,
    source                 TEXT NOT NULL DEFAULT 'Yahoo Finance via yfinance'
);

CREATE TABLE IF NOT EXISTS options_data.quote_snapshots (
    run_id                 BIGINT NOT NULL REFERENCES options_data.collection_runs(run_id),
    captured_at            TIMESTAMPTZ NOT NULL,
    underlying_symbol      TEXT NOT NULL,
    expiration_date        DATE NOT NULL,
    contract_symbol        TEXT NOT NULL,
    option_type            CHAR(1) NOT NULL CHECK (option_type IN ('C', 'P')),
    strike                 DOUBLE PRECISION NOT NULL,
    bid                    DOUBLE PRECISION NOT NULL CHECK (bid > 0),
    ask                    DOUBLE PRECISION NOT NULL CHECK (ask >= bid),
    last_price             DOUBLE PRECISION,
    implied_volatility     DOUBLE PRECISION,
    open_interest          BIGINT NOT NULL CHECK (open_interest >= 0),
    volume                 BIGINT,
    last_trade_at          TIMESTAMPTZ,
    in_the_money           BOOLEAN,
    underlying_price       DOUBLE PRECISION,
    PRIMARY KEY (run_id, contract_symbol)
);

CREATE INDEX IF NOT EXISTS idx_options_quotes_underlying_time
    ON options_data.quote_snapshots(underlying_symbol, captured_at DESC);
CREATE INDEX IF NOT EXISTS idx_options_quotes_contract_time
    ON options_data.quote_snapshots(contract_symbol, captured_at DESC);
CREATE INDEX IF NOT EXISTS idx_options_runs_started
    ON options_data.collection_runs(started_at DESC);

COMMIT;
